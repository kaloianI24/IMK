// site/src/loaders/testimonials.ts
//
// A collection that is legitimately EMPTY must not make the build complain.
//
// Until the first client consents there are no published testimonial files.
// Astro's glob loader treats that as "no such collection": it returns before
// registering anything, so `getCollection('testimonials')` later logs
//   The collection "testimonials" does not exist or is empty.
// and points at the content config — but the config is fine, the collection
// is simply empty, which is the expected state (RP-8.5 keeps the empty-state
// copy on the homepage for exactly this case).
//
// This loader delegates to Astro's glob loader and then guarantees the
// collection is registered, so an empty collection is quiet and
// `getCollection()` returns an empty array.
//
// It also swallows the two glob-loader messages that mean "this collection has
// no files yet" — the content directory is generated by
// scripts/publish-testimonials.mjs, so before the first publish it may not
// exist at all. Every other warning and error still surfaces.

import { glob } from 'astro/loaders';
import type { Loader, LoaderContext } from 'astro/loaders';

/** Where the publish script writes the published quotes. */
const BASE = './src/content/testimonials';
const PATTERN = '**/*.md';

/**
 * Placeholder id used to register the collection. It is removed again right
 * away: the content store keeps the (now empty) collection, which is all we
 * need — `getCollection()` then returns [] instead of warning.
 */
const EMPTY_SENTINEL_ID = '__empty__';

const globLoader = glob({ pattern: PATTERN, base: BASE });

/** True for the glob-loader messages that only mean "no files yet". */
function isExpectedEmptyMessage(message: string): boolean {
  if (message.startsWith('No files found matching')) return true;
  return message.startsWith('The base directory') && message.includes('does not exist');
}

/**
 * Wraps Astro's integration logger so the expected-empty messages are
 * dropped and everything else is passed through untouched.
 */
function withoutEmptyCollectionWarnings(
  logger: LoaderContext['logger'],
): LoaderContext['logger'] {
  return {
    info: (message: string) => logger.info(message),
    warn: (message: string) => {
      if (isExpectedEmptyMessage(message)) return;
      logger.warn(message);
    },
    error: (message: string) => logger.error(message),
    debug: (message: string) => logger.debug(message),
  } as unknown as LoaderContext['logger'];
}

export const testimonialsLoader: Loader = {
  name: 'testimonials-loader',
  async load(context: LoaderContext): Promise<void> {
    await globLoader.load({
      ...context,
      logger: withoutEmptyCollectionWarnings(context.logger),
    });

    // The glob loader returns early when it matches no files, so nothing was
    // written and the collection does not exist yet. Register it with a
    // placeholder that is removed again: the store keeps the empty
    // collection, so `getCollection()` returns [] instead of warning.
    context.store.set({ id: EMPTY_SENTINEL_ID, data: {} });
    context.store.delete(EMPTY_SENTINEL_ID);
  },
};
