import { defineCollection, z } from 'astro:content';
import { glob } from 'astro/loaders';
import { CTA_ROLES, TESTIMONIAL_MAX } from './types/contracts.js';
import { testimonialsLoader } from './loaders/testimonials.js';

const ctaSchema = z.enum([...CTA_ROLES]);

const howStep = z.object({ title: z.string().min(1).max(80), body: z.string().min(1).max(400) });
const faqItem = z.object({ q: z.string().min(1).max(240), a: z.string().min(1).max(1200) });

const services = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/services' }),
  schema: z.object({
    order: z.number().int().min(1).max(4),
    title: z.string().min(1).max(60),
    tagline: z.string().min(1).max(140),
    summary: z.string().min(1).max(260),
    whoFor: z.string().min(1).max(400),
    problem: z.string().min(1).max(600),
    deliverables: z.array(z.string().min(1).max(200)).min(3).max(8),
    howItWorks: z.array(howStep).min(3).max(5),
    inScope: z.array(z.string().min(1).max(200)).min(1).max(12),
    outOfScope: z.array(z.string().min(1).max(200)).min(1).max(12),
    timeline: z.string().min(1).max(120),
    startingAt: z.string().min(1).max(120),
    careOption: z.string().min(1).max(200),
    faq: z.array(faqItem).min(1).max(5),
    caseSnapshot: z.string().min(1).max(240),
    cta: ctaSchema,
  }),
});

const cases = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/cases' }),
  schema: z.object({
    order: z.number().int().min(1).max(3).optional(),
    title: z.string().min(1).max(80),
    sector: z.string().min(1).max(60),
    sample: z.literal(true),
    context: z.string().min(1).max(600),
    problem: z.string().min(1).max(600),
    approach: z.string().min(1).max(800),
    execution: z.array(z.string().min(1).max(300)).min(3).max(8),
    outcome: z.string().min(1).max(240),
    result: z.string().min(1).max(800),
    quote: z.object({ quote: z.string().min(1).max(600), name: z.string().min(1).max(80), role: z.string().min(1).max(120) }).optional(),
    cta: ctaSchema,
  }),
});

// Published client testimonials (spec RP-8.1).
// Files are generated by scripts/publish-testimonials.mjs from the moderation
// store — they are never hand-edited. Consent is enforced at publish time:
// a record without consent.p1 is never written, and a record without p2 is
// published anonymously (no name, no company, no badge).
//
// The loader is a thin wrapper around Astro's glob loader so that an EMPTY
// collection (no quotes published yet) stays registered and quiet instead of
// making every build warn that the collection "does not exist or is empty".
//
// The length caps come from the shared contracts (site/src/types/contracts.ts),
// NOT from local numbers: the server writes client-record fields under the
// same caps, and a mismatch breaks the build. Keep the two in step.
const testimonials = defineCollection({
  loader: testimonialsLoader,
  schema: z.object({
    name: z.string().min(1).max(TESTIMONIAL_MAX.name).optional(),
    company: z.string().min(1).max(TESTIMONIAL_MAX.company).optional(),
    role: z.string().min(1).max(TESTIMONIAL_MAX.role).optional(),
    rating: z.number().int().min(1).max(5).optional(),
    quote: z.string().min(1).max(TESTIMONIAL_MAX.quote),
    verified: z.boolean().default(false),
    source: z.enum(['portal', 'public']).default('portal'),
  }),
});

const blog = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/blog' }),
  schema: z.object({
    title: z.string().min(1).max(120),
    description: z.string().min(1).max(260),
    publishedAt: z.string().min(1).max(20),
    author: z.string().min(1).max(80).default('IMK'),
    tags: z.array(z.string().min(1).max(40)).min(1).max(6),
  }),
});

export const collections = { services, cases, testimonials, blog };